"""smoke_utils.py - quick PASS/FAIL smoke check of the qe_foundations.utils library.

Run it from the repository root, with your venv ACTIVE:
    python smoke_utils.py
Exit code 0 = all PASS, 1 = at least one FAIL.  (Do not edit this file.)
"""

import sys
from datetime import date

import requests  # third-party: proves your venv + requirements.txt work

from qe_foundations.utils import (
    add_days,
    clamp,
    days_between,
    is_valid_email,
    make_users,
    mask_email,
    slugify,
)


def check(label, ok):
    print(("PASS  " if ok else "FAIL  ") + label)
    return ok


def main():
    print("requests version:", requests.__version__)
    results = [
        check("slugify", slugify(" Login Page: Happy Path ") == "login-page-happy-path"),
        check("is_valid_email", is_valid_email("qa@example.com") and not is_valid_email("qa@@x")),
        check("mask_email", mask_email("tester@example.com") == "t***@example.com"),
        check("clamp", clamp(150, 0, 100) == 100),
        check("add_days", add_days(date(2025, 1, 31), 1) == date(2025, 2, 1)),
        check("days_between", days_between(date(2025, 1, 1), date(2025, 1, 31)) == 30),
        check("make_users is repeatable", make_users(3, seed=7) == make_users(3, seed=7)),
    ]
    print(f"{sum(results)}/{len(results)} checks passed")
    return 0 if all(results) else 1


if __name__ == "__main__":
    sys.exit(main())
