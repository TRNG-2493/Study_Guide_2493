"""
lab.py - Week 8 Wednesday exercise: AI-augmented QA lifecycle for ShopFront US-420.

Offline, standard library only. It PRINTS the prompts you paste into Claude and CHECKS what
comes back. Same commands as the demo's lifecycle_lab.py, pointed at the gift card story.

    python lab.py lint                               # deterministic weak-word baseline
    python lab.py review-prompt                      # Stage 1 prompt (requirements review)
    python lab.py check-findings FILE [--log review/question_log.md]
    python lab.py oracle                             # your expected results (Stage 2)
    python lab.py tc-prompt                          # Stage 3 prompt (carries PO answers)
    python lab.py check-suite FILE                   # review aids: trace matrix and pointers
    python lab.py review-template FILE               # writes review/review_decisions.json (blank)
    python lab.py signoff DRAFT DECISIONS.json       # Stage 4 gate
    python lab.py data-prompt                        # Stage 5 prompt
    python lab.py check-data FILE                    # independent data checks
    python lab.py preflight FILE --tool claude --cls internal
    python lab.py disclose --tool Claude --reviewer <you> [--what "test cases"]
Do not edit this file.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from qa_flow import data_checks, reqs_review, responsible, review_log, suite_checks
from qa_flow.stories import oracle_us420

HERE = Path(__file__).parent
STORY = "US-420"

# The inputs for your own expected-results table (Stage 2). Add rows if you like.
ORACLE_INPUTS = [
    (80.00, "QATEST26ABCD1234", 50.00),
    (80.00, "QATEST26ABCD1234", 80.00),
    (80.00, "QATEST26ABCD1234", 79.99),
    (80.00, "QATEST26ABCD1234", 80.01),
    (80.00, "QATEST26ABCD1234", 0.00),
    (80.00, "QATEST26ABCD123", 50.00),
    (80.00, "QATEST26ABCD12345", 50.00),
    (80.00, "QATEST26ABCD123!", 50.00),
    (80.00, "qatest26abcd1234", 50.00),
    (80.00, "QATEST26-ABCD-1234", 50.00),
]


def _read(path: str) -> str:
    return Path(path).read_text(encoding="utf-8")


def cmd_lint(_):
    for line in reqs_review.lint_requirements(STORY):
        print(line)


def cmd_review_prompt(_):
    print(reqs_review.build_review_prompt(STORY))


def cmd_check_findings(a):
    kept, report = reqs_review.check_findings(_read(a.file), STORY)
    print(f"{len(report)} findings received for {STORY}\n")
    for i, f, problems in report:
        print(f"{'OK  ' if not problems else 'FLAG'} #{i} {f.get('ac')} {f.get('category')}: {f.get('quote')!r}")
        for p in problems:
            print(f"       - {p}")
    print(f"\n{len(kept)} passed the automatic checks; {len(report) - len(kept)} flagged for a human.")
    cov = reqs_review.reference_coverage([f for _, f, _ in report], STORY)
    if not cov:
        print("\nREFERENCE_ISSUES is empty: write your own review in qa_flow/stories.py BEFORE prompting.")
    else:
        print("\nCompared with YOUR manual review (written before prompting):")
        for name, covered in cov:
            print(f"  {'found ' if covered else 'MISSED'}  {name}")
    if a.log:
        Path(a.log).write_text(f"# Question log: {STORY}\n\n" + reqs_review.build_question_log(kept, STORY)
                               + "\n", encoding="utf-8")
        print(f"\nQuestion log written to {a.log} ({len(kept)} questions, all OPEN).")


def cmd_oracle(_):
    print("US-420 expected results from YOUR oracle (write it BEFORE reading any AI draft)")
    print(f"{'total':>7} {'code':<20} {'balance':>7}  {'pays':>6} {'remain':>6}  message")
    for total, code, bal in ORACLE_INPUTS:
        try:
            want = oracle_us420(total, code, bal)
        except NotImplementedError as e:
            sys.exit(str(e))
        if want is None:
            print(f"{total:>7.2f} {code:<20} {bal:>7.2f}  {'?':>6} {'?':>6}  not decided: question for the PO")
        else:
            print(f"{total:>7.2f} {code:<20} {bal:>7.2f}  {want['gift_card_pays']:>6.2f} "
                  f"{want['remainder']:>6.2f}  {want['message'] or '-'}")


def cmd_tc_prompt(_):
    print(suite_checks.build_tc_prompt(STORY))


def cmd_check_suite(a):
    suite = suite_checks.parse_suite(_read(a.file))
    cases = suite["test_cases"]
    print(f"{len(cases)} test cases, {len(suite.get('open_questions', []))} open question(s) from Claude\n")
    forward, orphans = suite_checks.trace_matrix(cases, STORY)
    print("Traceability (forward: AC -> cases)")
    for ac, ids in forward.items():
        print(f"  {ac}: {', '.join(ids) if ids else 'NOT COVERED'}")
    for o in orphans:
        print(f"  backward: {o} points at no real AC")
    mix = suite_checks.suite_mix(cases)
    print("\nMix: " + ", ".join(f"{k} {mix.get(k, 0)}" for k in ("positive", "negative", "boundary")))
    print("Boundaries: " + ", ".join(f"{v} {'yes' if ok else 'NO'}"
                                     for v, ok in suite_checks.boundary_values_present(cases).items()))
    print("\nPointers for the reviewer (code points, the human decides)")
    try:
        pointers = suite_checks.review_pointers(cases, STORY)
    except NotImplementedError as e:
        sys.exit(f"{e}\n(check-suite recomputes expected results with your oracle)")
    for cid, ps in pointers.items():
        print(f"  {cid}: {'no pointers - still read it' if not ps else ps[0]}")
        for p in ps[1:]:
            print(f"  {'':{len(cid)}}  {p}")
    for q in suite.get("open_questions", []):
        print(f"\nClaude open question: {q}")


def cmd_review_template(a):
    cases = suite_checks.parse_suite(_read(a.file))["test_cases"]
    out = Path(a.out)
    if out.exists():
        sys.exit(f"{out} already exists: refusing to overwrite your decisions")
    out.write_text(json.dumps(review_log.decisions_template(cases, STORY), indent=2) + "\n", encoding="utf-8")
    print(f"Blank decision file written to {out}: one TODO entry per AI item.")


def cmd_signoff(a):
    cases = suite_checks.parse_suite(_read(a.draft))["test_cases"]
    review = review_log.load_decisions(a.decisions)
    out = HERE / "review"
    try:
        metrics = review_log.signoff(cases, review, out)
    except review_log.ReviewError as e:
        print("SIGN-OFF REFUSED. Fix these and run again:")
        for line in str(e).splitlines():
            print(f"  - {line}")
        sys.exit(1)
    print("Sign-off OK: review/approved_suite.json and review/correction_log.csv written.\n")
    for line in metrics:
        print(line)


def cmd_data_prompt(a):
    print(data_checks.build_data_prompt(a.n))


def cmd_check_data(a):
    rows, questions = data_checks.parse_rows(_read(a.file))
    print(f"{len(rows)} rows, {len(questions)} question(s) from Claude")
    try:
        problems = data_checks.check_rows(rows, a.n)
    except NotImplementedError as e:
        sys.exit(str(e))
    for p in problems:
        print("PROBLEM:", p)
    if not problems:
        print("No mechanical problems found.")
    print("Still read every row: a script cannot judge relevance or spot a real-looking value it was not told about.")
    for q in questions:
        print("Claude question:", q)


def cmd_preflight(a):
    ok, to_send, why = responsible.preflight(_read(a.file), a.tool, a.cls)
    print(f"tool={a.tool} class={a.cls} allowed={ok}")
    for r in why:
        print(f"  - {r}")
    if ok:
        print("\n--- text you may paste (after you have READ it) ---")
        print(to_send)


def cmd_disclose(a):
    print(responsible.disclosure(a.tool, a.reviewer, a.date, a.what))


def main():
    p = argparse.ArgumentParser(description="Week 8 Wednesday exercise lab (US-420)")
    sub = p.add_subparsers(dest="cmd", required=True)
    for name, fn in (("lint", cmd_lint), ("review-prompt", cmd_review_prompt), ("oracle", cmd_oracle),
                     ("tc-prompt", cmd_tc_prompt)):
        sub.add_parser(name).set_defaults(fn=fn)
    s = sub.add_parser("check-findings"); s.add_argument("file"); s.add_argument("--log")
    s.set_defaults(fn=cmd_check_findings)
    s = sub.add_parser("check-suite"); s.add_argument("file"); s.set_defaults(fn=cmd_check_suite)
    s = sub.add_parser("review-template"); s.add_argument("file")
    s.add_argument("--out", default="review/review_decisions.json"); s.set_defaults(fn=cmd_review_template)
    s = sub.add_parser("signoff"); s.add_argument("draft"); s.add_argument("decisions")
    s.set_defaults(fn=cmd_signoff)
    for name, fn in (("data-prompt", cmd_data_prompt), ("check-data", cmd_check_data)):
        s = sub.add_parser(name)
        if name == "check-data":
            s.add_argument("file")
        s.add_argument("-n", type=int, default=3, help="rows per category")
        s.set_defaults(fn=fn)
    s = sub.add_parser("preflight"); s.add_argument("file")
    s.add_argument("--tool", default="claude"); s.add_argument("--cls", default="internal")
    s.set_defaults(fn=cmd_preflight)
    s = sub.add_parser("disclose"); s.add_argument("--tool", required=True)
    s.add_argument("--reviewer", required=True); s.add_argument("--date"); s.add_argument("--what", default="test cases")
    s.set_defaults(fn=cmd_disclose)
    a = p.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
