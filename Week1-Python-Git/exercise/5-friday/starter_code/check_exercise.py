ROWS = [
    {"test_id": "TC-001", "status": "PASS", "duration": 1.2},
    {"test_id": "TC-002", "status": "FAIL", "duration": 3.4, "message": "Timeout, retry failed"},
    {"test_id": "TC-003", "status": "PASS", "duration": 0.8},
    {"test_id": "TC-004", "status": "SKIPPED"},
]


def raises(exc_type, func, *args):
    """Assert that func(*args) raises exc_type. Returns the message."""
    try:
        func(*args)
    except exc_type as error:
        return str(error)
    except NotImplementedError:
        raise  # your TODO is not finished yet: reported as TODO, not FAIL
    except Exception as error:  # wrong kind of error
        raise AssertionError(
            f"expected {exc_type.__name__} but got {type(error).__name__}: {error}"
        )
    raise AssertionError(f"expected {exc_type.__name__} but nothing was raised")


def make_suite():
    return Suite.from_rows("Login", ROWS)


# ---------------- Part 1: TestResult ----------------
def t1_basic_construction():
    r = TestResult("TC-001", "PASS", 1.2)
    assert r.test_id == "TC-001", f"test_id should be 'TC-001', got {r.test_id!r}"
    assert r.status == "PASS", f"status should be 'PASS', got {r.status!r}"
    assert r.duration == 1.2, f"duration should be 1.2, got {r.duration!r}"
    d = TestResult("TC-002", "FAIL")
    assert d.duration == 0.0 and d.message == "", "duration defaults to 0.0, message to ''"


def t1_status_normalised():
    r = TestResult("TC-001", "  pass ")
    assert r.status == "PASS", f"' pass ' should become 'PASS', got {r.status!r}"


def t1_status_validation():
    msg = raises(ValueError, TestResult, "TC-001", "PSAS")
    assert "PSAS" in msg, "error message should include the bad value"
    raises(ValueError, TestResult, "TC-001", 5)
    r = TestResult("TC-001", "PASS")
    raises(ValueError, setattr, r, "status", "nope")
    assert r.status == "PASS", "a rejected assignment must leave the old status"
    r.status = "fail"
    assert r.status == "FAIL", "the setter should also normalise"


def t1_duration_validation():
    raises(ValueError, TestResult, "TC-001", "PASS", -0.1)
    raises(TypeError, TestResult, "TC-001", "PASS", "fast")
    raises(TypeError, TestResult, "TC-001", "PASS", True)
    r = TestResult("TC-001", "PASS", 2)
    assert isinstance(r.duration, float), "duration should be stored as a float"


def t1_test_id_rules():
    assert TestResult.is_valid_id("TC-001") is True
    for bad in ("tc-001", "TC-", "TC-12a", "XX-001", "", None, 42):
        assert TestResult.is_valid_id(bad) is False, f"{bad!r} should be invalid"
    raises(ValueError, TestResult, "bad", "PASS")
    r = TestResult("TC-001", "PASS")
    raises(AttributeError, setattr, r, "test_id", "TC-999")  # read-only property


def t1_is_passed_property():
    assert TestResult("TC-001", "PASS").is_passed is True
    assert TestResult("TC-002", "FAIL").is_passed is False
    raises(AttributeError, setattr, TestResult("TC-003", "PASS"), "is_passed", False)


def t1_class_counter():
    before = TestResult.how_many()
    TestResult("TC-001", "PASS")
    TestResult("TC-002", "FAIL")
    assert TestResult.how_many() == before + 2, "how_many() should grow by 1 per object"
    try:
        TestResult("TC-003", "PSAS")
    except ValueError:
        pass
    assert TestResult.how_many() == before + 2, \
        "an object that failed validation must NOT be counted"
    assert TestResult.total_created == TestResult.how_many()


def t1_from_dict():
    r = TestResult.from_dict({"test_id": "TC-005", "status": "fail", "duration": 2.5, "message": "boom"})
    assert (r.test_id, r.status, r.duration, r.message) == ("TC-005", "FAIL", 2.5, "boom")
    r2 = TestResult.from_dict({"test_id": "TC-006", "status": "PASS"})
    assert r2.duration == 0.0 and r2.message == "", "optional keys use defaults"
    msg = raises(ValueError, TestResult.from_dict, {"status": "PASS"})
    assert "test_id" in msg, "message should name the missing key"

    class SpecialResult(TestResult):
        pass

    assert type(SpecialResult.from_dict({"test_id": "TC-007", "status": "PASS"})) is SpecialResult, \
        "from_dict must build 'cls', not a hard-coded TestResult"


def t1_from_csv_line():
    r = TestResult.from_csv_line("TC-010, PASS, 1.5, Slow login, but fine")
    assert r.test_id == "TC-010" and r.status == "PASS" and r.duration == 1.5
    assert r.message == "Slow login, but fine", f"message keeps its commas, got {r.message!r}"
    r2 = TestResult.from_csv_line("TC-011,SKIPPED")
    assert r2.duration == 0.0 and r2.message == ""
    raises(ValueError, TestResult.from_csv_line, "TC-012")


def t1_text_forms():
    r = TestResult("TC-001", "PASS", 1.2)
    assert str(r) == "TC-001 PASS 1.2s", f"str() gave {str(r)!r}"
    r.message = "ok"
    assert str(r) == "TC-001 PASS 1.2s - ok", f"str() with message gave {str(r)!r}"
    assert repr(r) == "TestResult('TC-001', 'PASS', 1.2)", f"repr() gave {repr(r)!r}"


# ---------------- Part 2: Suite ----------------
def t2_construction():
    s = Suite("  Login ")
    assert s.name == "Login" and s.count() == 0
    raises(ValueError, Suite, "   ")
    raises(ValueError, Suite, 123)


def t2_add_rules():
    s = Suite("S")
    s.add(TestResult("TC-001", "PASS"))
    assert s.count() == 1
    raises(TypeError, s.add, {"test_id": "TC-002", "status": "PASS"})
    msg = raises(ValueError, s.add, TestResult("TC-001", "FAIL"))
    assert "TC-001" in msg, "duplicate message should mention the id"
    assert s.count() == 1


def t2_results_is_a_copy():
    s = make_suite()
    copy = s.results
    copy.append("junk")
    assert s.count() == 4, "changing the returned list must not change the suite"
    other = Suite("Other")
    assert other.count() == 0, "each Suite needs its OWN list (not shared)"


def t2_pass_rate():
    assert Suite("Empty").pass_rate == 0.0, "empty suite: 0.0, not a crash"
    assert abs(make_suite().pass_rate - 50.0) < 1e-9, "2 PASS out of 4 results = 50.0"
    raises(AttributeError, setattr, make_suite(), "pass_rate", 99)


def t2_duration_and_counts():
    s = make_suite()
    assert abs(s.total_duration - 5.4) < 1e-9, f"total_duration was {s.total_duration}"
    counts = s.counts_by_status()
    assert counts == {"PASS": 2, "FAIL": 1, "SKIPPED": 1, "ERROR": 0}, f"got {counts}"


def t2_failures_and_slowest():
    s = make_suite()
    s.add(TestResult("TC-005", "ERROR", 0.1))
    assert [r.test_id for r in s.failures()] == ["TC-002", "TC-005"], "FAIL and ERROR count"
    assert [r.test_id for r in s.slowest()] == ["TC-002"], "default n=1"
    assert [r.test_id for r in s.slowest(2)] == ["TC-002", "TC-001"]
    assert len(s.slowest(99)) == 5, "n larger than the suite just returns everything"


def t2_from_rows():
    s = Suite.from_rows("Smoke", ROWS)
    assert isinstance(s, Suite) and s.name == "Smoke" and s.count() == 4
    raises(ValueError, Suite.from_rows, "Bad", [{"test_id": "TC-001", "status": "NOPE"}])


# ---------------- Part 3: Reporters ----------------
def t3_static_helpers():
    assert Reporter.pad("ab", 5) == "ab   ", "pad should left-justify to width"
    assert Reporter.pad("abcdef", 3) == "abcdef", "pad never cuts text"
    assert Reporter.pad(42, 4) == "42  ", "pad should accept non-text"
    assert Reporter.format_percent(66.666) == "66.7%"
    assert CsvReporter.clean_cell("a,b\nc") == "a;b c"


def t3_base_class():
    raises(TypeError, Reporter, "not a suite")
    base = Reporter(make_suite())
    msg = raises(NotImplementedError, base.render)
    assert msg != "", "give NotImplementedError a helpful message"


def t3_inheritance_links():
    assert issubclass(TextReporter, Reporter) and issubclass(CsvReporter, Reporter)
    r = TextReporter(make_suite())
    assert r.suite.name == "Login", "subclasses reuse the base __init__"


def t3_text_reporter():
    lines = TextReporter(make_suite()).render().split("\n")
    assert lines[0] == "=== Login ===", f"header line was {lines[0]!r}"
    assert lines[1] == "TC-001  PASS       1.2s", f"row line was {lines[1]!r}"
    assert lines[4] == "TC-004  SKIPPED    0.0s", f"row line was {lines[4]!r}"
    assert lines[-1] == "Pass rate: 50.0%", f"last line was {lines[-1]!r}"
    assert len(lines) == 6, f"expected 6 lines, got {len(lines)}"


def t3_csv_reporter():
    lines = CsvReporter(make_suite()).render().split("\n")
    assert lines[0] == "test_id,status,duration,message", f"header was {lines[0]!r}"
    assert lines[1] == "TC-001,PASS,1.2,", f"row was {lines[1]!r}"
    assert lines[2] == "TC-002,FAIL,3.4,Timeout; retry failed", f"row was {lines[2]!r}"
    assert len(lines) == 5, f"expected 5 lines, got {len(lines)}"


def t3_polymorphism():
    suite = make_suite()
    outputs = []
    for reporter in [TextReporter(suite), CsvReporter(suite)]:
        outputs.append(reporter.render())  # same call, different behaviour
    assert outputs[0] != outputs[1]
    assert TextReporter(suite).line_count() == 6
    assert CsvReporter(suite).line_count() == 5, "line_count() lives in the base class"
    assert "line_count" not in TextReporter.__dict__ and "line_count" not in CsvReporter.__dict__, \
        "do not copy line_count into the subclasses; inherit it"


def t3_reporters_do_not_change_suite():
    suite = make_suite()
    TextReporter(suite).render()
    CsvReporter(suite).render()
    assert suite.count() == 4 and suite.results[0].status == "PASS"


PARTS = {
    "1": ("Part 1 - TestResult", [
        t1_basic_construction, t1_status_normalised, t1_status_validation,
        t1_duration_validation, t1_test_id_rules, t1_is_passed_property,
        t1_class_counter, t1_from_dict, t1_from_csv_line, t1_text_forms]),
    "2": ("Part 2 - Suite", [
        t2_construction, t2_add_rules, t2_results_is_a_copy, t2_pass_rate,
        t2_duration_and_counts, t2_failures_and_slowest, t2_from_rows]),
    "3": ("Part 3 - Reporters", [
        t3_static_helpers, t3_base_class, t3_inheritance_links, t3_text_reporter,
        t3_csv_reporter, t3_polymorphism, t3_reporters_do_not_change_suite]),
}


def main():
    wanted = sys.argv[1:] or sorted(PARTS)
    passed = failed = todo = 0
    for key in wanted:
        if key not in PARTS:
            print(f"Unknown part {key!r}; use 1, 2 or 3.")
            return 2
        title, checks = PARTS[key]
        print(f"\n{title}")
        for check in checks:
            name = check.__name__
            try:
                check()
            except NotImplementedError as error:
                todo += 1
                print(f"  TODO  {name}: not implemented yet ({error})")
            except AssertionError as error:
                failed += 1
                print(f"  FAIL  {name}: {error}")
            except Exception as error:
                failed += 1
                print(f"  FAIL  {name}: crashed with {type(error).__name__}: {error}")
            else:
                passed += 1
                print(f"  ok    {name}")
    total = passed + failed + todo
    print(f"\n{passed}/{total} checks passed ({failed} failed, {todo} still TODO)")
    return 0 if passed == total else 1


if __name__ == "__main__":
    sys.exit(main())
