"""PriceService: small client for an EXTERNAL tax / currency API (code under test for the mock tasks).

Do not edit this file. Assumed external API (it does not exist locally, so you must mock it):
    GET {base_url}/tax/{country}              -> 200 {"country": "DE", "rate": 0.19}
    GET {base_url}/rates?base=USD&symbols=EUR -> 200 {"base": "USD", "rates": {"EUR": 0.92}}
Behaviour:
    * HTTP 200      -> parsed JSON is used
    * HTTP 429      -> retried up to `max_retries` times, waiting Retry-After seconds (default 1)
                       between attempts; still 429 afterwards -> RateLimitError
    * HTTP 5xx/4xx  -> PriceServiceError (NOT retried)
    * network timeout -> PriceServiceTimeout (NOT retried)
"""
import time

import requests


class PriceServiceError(Exception):
    """The external API answered with an error status or an unusable body."""


class PriceServiceTimeout(PriceServiceError):
    """The external API did not answer in time."""


class RateLimitError(PriceServiceError):
    """Still HTTP 429 after all retries were used."""


class PriceService:
    def __init__(self, base_url="https://prices.example.test", timeout=2.0,
                 max_retries=2, session=None, sleep=time.sleep):
        self.base_url = base_url.rstrip("/")
        self.timeout = timeout
        self.max_retries = max_retries
        self.session = session or requests.Session()
        self._sleep = sleep  # injectable so tests never really wait

    def _get_json(self, path, params=None):
        url = f"{self.base_url}{path}"
        attempt = 0
        while True:
            try:
                resp = self.session.get(url, params=params, timeout=self.timeout)
            except requests.exceptions.Timeout as exc:
                raise PriceServiceTimeout(f"timeout calling {url}") from exc
            except requests.exceptions.ConnectionError as exc:
                raise PriceServiceError(f"cannot reach {url}") from exc
            if resp.status_code == 429:
                if attempt >= self.max_retries:
                    raise RateLimitError(f"rate limited after {attempt} retries")
                attempt += 1
                self._sleep(float(resp.headers.get("Retry-After", 1)))
                continue
            if resp.status_code != 200:
                raise PriceServiceError(f"unexpected status {resp.status_code} from {url}")
            try:
                return resp.json()
            except ValueError as exc:
                raise PriceServiceError("response body is not JSON") from exc

    def get_tax_rate(self, country):
        """Tax rate as a fraction, e.g. 0.19. Country code is upper-cased."""
        data = self._get_json(f"/tax/{country.upper()}")
        if "rate" not in data:
            raise PriceServiceError("missing 'rate' in response")
        return float(data["rate"])

    def price_with_tax(self, net_price, country):
        """net_price * (1 + rate), rounded to 2 decimals. Negative prices -> ValueError."""
        if net_price < 0:
            raise ValueError("net_price must be >= 0")
        return round(net_price * (1 + self.get_tax_rate(country)), 2)

    def convert(self, amount, base, target):
        """Convert `amount` from currency `base` to `target`, rounded to 2 decimals."""
        data = self._get_json("/rates", params={"base": base.upper(), "symbols": target.upper()})
        try:
            rate = data["rates"][target.upper()]
        except KeyError as exc:
            raise PriceServiceError(f"no rate for {target}") from exc
        return round(amount * float(rate), 2)
