"""Local practice shop used as the app under test for this exercise (works offline).

It is a single-file stand-in for a small e-commerce site: login, product list with
sorting, cart, three-step checkout.  Elements carry `data-test="..."` attributes.
Adapted from the Wednesday demo mock, copied here so this folder is self-contained.

You do NOT edit this file.  `conftest.py` starts it automatically on
http://127.0.0.1:8791 when you run pytest.  To start it by hand:

    python -m app.mock_shop            # from the starter_code/ folder
"""
import sys
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

PAGE = r"""<!doctype html><html><head><meta charset="utf-8"><title>Practice Shop (mock)</title></head>
<body><div id="app"></div>
<script>
const PRODUCTS = ["Sauce Labs Backpack","Sauce Labs Bike Light","Sauce Labs Bolt T-Shirt",
  "Sauce Labs Fleece Jacket","Sauce Labs Onesie","Test.allTheThings() T-Shirt (Red)"];
const PRICES = [29.99, 9.99, 15.99, 49.99, 7.99, 15.99];
const USERS = {standard_user:1, locked_out_user:1, problem_user:1, performance_glitch_user:1};
const slug = n => n.toLowerCase().replace(/\(|\)|\./g,"").replace(/ /g,"-");
const get = (k, d) => JSON.parse(localStorage.getItem(k) || JSON.stringify(d));
const set = (k, v) => localStorage.setItem(k, JSON.stringify(v));
const go = p => { location.href = p; };
const app = document.getElementById("app");
const path = location.pathname;
const cart = () => get("cart", []);
const header = () => `<div><span class="title">Practice Shop</span>
  <a data-test="shopping-cart-link" href="/cart.html">Cart${cart().length ?
  `<span data-test="shopping-cart-badge">${cart().length}</span>` : ""}</a></div>`;
const items = (list, withButtons) => list.map(n => `<div data-test="inventory-item">
  <div data-test="inventory-item-name">${n}</div>
  <div data-test="inventory-item-price">$${PRICES[PRODUCTS.indexOf(n)]}</div>
  ${withButtons ? `<button data-test="${cart().includes(n) ? "remove-" : "add-to-cart-"}${slug(n)}">
     ${cart().includes(n) ? "Remove" : "Add to cart"}</button>` : ""}</div>`).join("");
const authed = () => get("user", null);
if (path !== "/" && !authed()) {
  app.innerHTML = `<div data-test="error">Epic sadface: You can only access '${path}' when you are logged in.</div>`;
} else if (path === "/") {
  app.innerHTML = `<input data-test="username" placeholder="Username"><input data-test="password" type="password" placeholder="Password">
    <div data-test="error" hidden></div><input type="button" data-test="login-button" value="Login">`;
  const err = m => { const e = document.querySelector("[data-test=error]"); e.hidden = false; e.textContent = "Epic sadface: " + m; };
  document.querySelector("[data-test=login-button]").onclick = () => {
    const u = document.querySelector("[data-test=username]").value, p = document.querySelector("[data-test=password]").value;
    if (!u) return err("Username is required");
    if (!p) return err("Password is required");
    if (!USERS[u] || p !== "secret_sauce") return err("Username and password do not match any user in this service");
    if (u === "locked_out_user") return err("Sorry, this user has been locked out.");
    set("user", u); set("cart", []); go("/inventory.html");
  };
} else if (path === "/inventory.html") {
  app.innerHTML = header() + `<select data-test="product-sort-container"><option value="az">Name (A to Z)</option>
    <option value="za">Name (Z to A)</option><option value="lohi">Price (low to high)</option>
    <option value="hilo">Price (high to low)</option></select><div id="list"></div>`;
  const draw = s => {
    let l = PRODUCTS.slice();
    if (s === "za") l.reverse();
    if (s === "lohi") l.sort((a, b) => PRICES[PRODUCTS.indexOf(a)] - PRICES[PRODUCTS.indexOf(b)]);
    if (s === "hilo") l.sort((a, b) => PRICES[PRODUCTS.indexOf(b)] - PRICES[PRODUCTS.indexOf(a)]);
    document.getElementById("list").innerHTML = items(l, true);
  };
  draw("az");
  document.querySelector("select").onchange = e => draw(e.target.value);
  document.getElementById("list").onclick = e => {
    const id = e.target.getAttribute("data-test") || ""; const c = cart();
    for (const n of PRODUCTS) {
      if (id === "add-to-cart-" + slug(n)) set("cart", [...c, n]);
      if (id === "remove-" + slug(n)) set("cart", c.filter(x => x !== n));
    }
    location.reload();
  };
} else if (path === "/cart.html") {
  app.innerHTML = header() + items(cart(), false) + `<button data-test="checkout">Checkout</button>`;
  document.querySelector("[data-test=checkout]").onclick = () => go("/checkout-step-one.html");
} else if (path === "/checkout-step-one.html") {
  app.innerHTML = header() + `<input data-test="firstName" placeholder="First Name"><input data-test="lastName" placeholder="Last Name">
    <input data-test="postalCode" placeholder="Zip/Postal Code"><div data-test="error" hidden></div>
    <input type="button" data-test="continue" value="Continue">`;
  document.querySelector("[data-test=continue]").onclick = () => {
    const f = n => document.querySelector(`[data-test=${n}]`).value;
    const need = [["firstName","First Name"],["lastName","Last Name"],["postalCode","Postal Code"]].find(x => !f(x[0]));
    if (need) { const e = document.querySelector("[data-test=error]"); e.hidden = false; e.textContent = `Error: ${need[1]} is required`; return; }
    go("/checkout-step-two.html");
  };
} else if (path === "/checkout-step-two.html") {
  app.innerHTML = header() + items(cart(), false) + `<button data-test="finish">Finish</button>`;
  document.querySelector("[data-test=finish]").onclick = () => { set("cart", []); go("/checkout-complete.html"); };
} else if (path === "/checkout-complete.html") {
  app.innerHTML = header() + `<h2 data-test="complete-header">Thank you for your order!</h2>`;
}
</script></body></html>"""


class Handler(BaseHTTPRequestHandler):
    def do_GET(self):
        body = PAGE.encode()
        self.send_response(200)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def log_message(self, *args):
        pass


if __name__ == "__main__":
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 8791
    print(f"Mock SauceDemo on http://127.0.0.1:{port}  (Ctrl+C to stop)")
    ThreadingHTTPServer(("127.0.0.1", port), Handler).serve_forever()
