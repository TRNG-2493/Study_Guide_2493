def is_valid_username(name):
    """True if name is 3-15 characters, ASCII letters/digits/underscore only,
    and does not start with a digit. Raises TypeError if name is not a string."""
    if not isinstance(name, str):
        raise TypeError("username must be a string")
    if not 3 <= len(name) <= 15:
        return False
    if name[0].isdigit():
        return False
    return all(ch.isascii() and (ch.isalnum() or ch == "_") for ch in name)


def calculate_cart_total(prices, tax_rate=0.0):
    """Sum the prices, add tax (tax_rate 0.10 means 10%), round to 2 decimals.
    Raises ValueError if tax_rate is negative or any price is negative."""
    if tax_rate < 0:
        raise ValueError("tax_rate must not be negative")
    if any(p < 0 for p in prices):
        raise ValueError("prices must not be negative")
    return round(sum(prices) * (1 + tax_rate), 2)


def celsius_to_fahrenheit(celsius):
    """Convert degrees Celsius to degrees Fahrenheit."""
    return celsius * 9 / 5 + 32


def letter_grade(score):
    """Map a 0-100 score to a letter: 90+ A, 80+ B, 70+ C, 60+ D, else F.
    Raises ValueError if score is outside 0-100."""
    if not 0 <= score <= 100:
        raise ValueError("score must be between 0 and 100")
    if score >= 90:
        return "A"
    if score >= 80:
        return "B"
    if score >= 70:
        return "C"
    if score >= 60:
        return "D"
    return "F"


def count_words(text):
    """Count whitespace-separated words. Raises TypeError if text is not a string."""
    if not isinstance(text, str):
        raise TypeError("text must be a string")
    return len(text.split())


def truncate(text, max_len):
    """Return text unchanged if it fits in max_len characters; otherwise cut it so
    the result (including a trailing '...') is exactly max_len characters long.
    Raises ValueError if max_len is less than 3."""
    if max_len < 3:
        raise ValueError("max_len must be at least 3")
    if len(text) >= max_len:
        return text[: max_len - 3] + "..."
    return text
